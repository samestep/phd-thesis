"""Convert a TextMate grammar (.tmLanguage.json) to a .sublime-syntax, the
format Typst's `raw(syntaxes: ...)` loads. Covers what Moss's grammar uses:
`match`, `begin`/`end`, captures, `patterns`, and repository includes.

    python3 tmlanguage-to-sublime.py moss.tmLanguage.json > moss.sublime-syntax

Needs PyYAML. `moss.sublime-syntax` beside this script is generated by it
from the grammar of the Moss revision in flake.lock, and `nix flake check`
checks that it still is. To regenerate it:

    nix build .#moss-syntax && cat result > syntaxes/moss.sublime-syntax
"""

import json
import sys

import yaml


def captures(caps):
    return {int(k): v["name"] for k, v in caps.items() if "name" in v}


def convert(patterns):
    out = []
    for p in patterns:
        if "include" in p:
            out.append({"include": p["include"].removeprefix("#")})
        elif "match" in p:
            rule = {"match": p["match"]}
            if "name" in p:
                rule["scope"] = p["name"]
            if "captures" in p:
                rule["captures"] = captures(p["captures"])
            out.append(rule)
        elif "begin" in p:
            rule = {"match": p["begin"]}
            if caps := p.get("beginCaptures", p.get("captures")):
                rule["captures"] = captures(caps)
            body = [{"meta_scope": p["name"]}] if "name" in p else []
            end = {"match": p["end"], "pop": True}
            if caps := p.get("endCaptures", p.get("captures")):
                end["captures"] = captures(caps)
            rule["push"] = [*body, end, *convert(p.get("patterns", []))]
            out.append(rule)
        elif "patterns" in p:
            out += convert(p["patterns"])
        else:
            sys.exit(f"unsupported pattern: {p}")
    return out


grammar = json.load(open(sys.argv[1]))
contexts = {"main": convert(grammar["patterns"])}
for key, value in grammar["repository"].items():
    contexts[key] = convert(value.get("patterns", [value]))
syntax = {
    "name": grammar["name"],
    "scope": grammar["scopeName"],
    "file_extensions": grammar["fileTypes"],
    "contexts": contexts,
}
print("%YAML 1.2\n---")
print("# Generated by tmlanguage-to-sublime.py from Moss's")
print("# vscode/syntaxes/moss.tmLanguage.json, at the revision in flake.lock.")
print(yaml.safe_dump(syntax, sort_keys=False, width=1000), end="")
